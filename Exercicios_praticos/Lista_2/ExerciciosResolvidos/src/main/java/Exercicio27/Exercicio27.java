public class Exercicio27 {
    
    public static double potencia(int valor1, int valor2){
       return valor1 ^ valor2;
    }
    
    public static void main(String[] args) {
       int valor1 = 22;
       int valor2 = 13;
       System.out.println("Potencia? " + potencia (valor1, valor2));
    }
}
